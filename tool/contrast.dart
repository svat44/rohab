// Prints the contrast table. Usage:
//   dart run tool/contrast.dart > docs/design-audit/contrast.md
import 'dart:io';

import 'package:rohab/theme/palette_values.dart';

String hex(int c) => '#${(c & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

void main() {
  stdout.writeln('# Contrast table\n');
  stdout.writeln('Generated by `dart run tool/contrast.dart`. WCAG 2 AA: 4.5:1 for text, 3:1 for large text and UI edges.');
  stdout.writeln('`test/contrast_test.dart` fails if any row drops below its minimum.\n');
  stdout.writeln('| Pair | Foreground | Background | Ratio | Minimum | Result |');
  stdout.writeln('|---|---|---|---|---|---|');
  var failed = 0;
  for (final p in contrastPairs) {
    final ok = p.ratio >= p.min;
    if (!ok) failed++;
    stdout.writeln('| ${p.name} | ${hex(p.fg)} | ${hex(p.bg)} | ${p.ratio.toStringAsFixed(2)}:1 | ${p.min}:1 | ${ok ? 'pass' : 'FAIL'} |');
  }
  stdout.writeln('\nFailures: $failed');
  exitCode = failed == 0 ? 0 : 1;
}
